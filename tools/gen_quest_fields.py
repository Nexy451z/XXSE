#!/usr/bin/env python3
"""docs/quest_fields.json -> crates/mhnx-core/src/questfields.rs"""
import json, os, re, sys

J = r"C:\anyWorkspace\nx\mhxx\mhnxeditor\docs\quest_fields.json"
O = r"C:\anyWorkspace\nx\mhxx\mhnxeditor\crates\mhnx-core\src\questfields.rs"

spec = json.load(open(J, encoding="utf-8"))
mib = spec["mib"]["fields"]
enums = spec.get("enums", {})

def esc(s):
    return (s or "").replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ").replace("\r", " ")

# enum tables
enum_lines = []
enum_names = []
for name, val in enums.items():
    if name == "source":
        continue
    if not isinstance(val, list):
        continue
    labels = []
    for e in val:
        if isinstance(e, dict):
            lab = e.get("ja") or e.get("label") or e.get("name") or ""
            v = e.get("value", e.get("id", ""))
            labels.append("%s=%s" % (lab, v) if v != "" else lab)
        else:
            labels.append(str(e))
    enum_names.append((name, labels))
    enum_lines.append("/// enum %s" % name)
    enum_lines.append("pub static ENUM_%s: &[&str] = &[%s];" % (name.upper(), ", ".join('"%s"' % esc(l) for l in labels)))
    enum_lines.append("")

def enum_for(note):
    m = re.search(r"enums\.(\w+)", note or "")
    if not m:
        return None
    n = m.group(1)
    return n if any(n == k for k, _ in enum_names) else None

field_lines = []
for f in mib:
    ty = (f.get("type") or "u8").strip()
    size = int(f.get("size") or 1)
    if ty.startswith("char") or ty.startswith("u8[") or ty == "struct":
        kind = "Bytes"
    elif ty.startswith("f32"):
        kind = "F32"
    elif ty.startswith("i"):
        kind = {1: "I8", 2: "I16", 4: "I32"}.get(size, "Bytes")
    else:
        kind = {1: "U8", 2: "U16", 4: "U32"}.get(size, "Bytes")
    en = enum_for(f.get("note"))
    field_lines.append(
        '    FieldDef { offset: %d, size: %d, kind: FieldKind::%s, key: "%s", ja: "%s", ui: "%s", enum_name: %s, confidence: "%s", note: "%s" },'
        % (
            int(f.get("offset", 0)), size, kind,
            esc(f.get("key")), esc(f.get("ja")), esc(f.get("ui")),
            ('Some("%s")' % en) if en else "None",
            esc(f.get("confidence")), esc((f.get("note") or "")[:180]),
        )
    )

out = []
out.append("//! Quest parameter (.mib) field table.")
out.append("//!")
out.append("//! @generated by tools/gen_quest_fields.py from docs/quest_fields.json - DO NOT EDIT.")
out.append("//! The offsets and enum mappings were derived from the Quedixx editor and")
out.append("//! verified against all 141 shipped quest archives.")
out.append("#![allow(clippy::all)]")
out.append("")
out.append("/// How a field is stored.")
out.append("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
out.append("pub enum FieldKind {")
out.append("    /// Single byte.")
out.append("    U8,")
out.append("    /// Signed single byte.")
out.append("    I8,")
out.append("    /// Little endian 16 bit.")
out.append("    U16,")
out.append("    /// Little endian signed 16 bit.")
out.append("    I16,")
out.append("    /// Little endian 32 bit.")
out.append("    U32,")
out.append("    /// Little endian signed 32 bit.")
out.append("    I32,")
out.append("    /// IEEE754 single precision.")
out.append("    F32,")
out.append("    /// Free bytes.")
out.append("    Bytes,")
out.append("}")
out.append("")
out.append("/// One field of a .mib record.")
out.append("#[derive(Debug, Clone, Copy)]")
out.append("pub struct FieldDef {")
out.append("    /// Byte offset inside the record.")
out.append("    pub offset: usize,")
out.append("    /// Size in bytes.")
out.append("    pub size: usize,")
out.append("    /// Storage type.")
out.append("    pub kind: FieldKind,")
out.append("    /// Machine readable name.")
out.append("    pub key: &'static str,")
out.append("    /// Japanese label.")
out.append("    pub ja: &'static str,")
out.append("    /// Quedixx UI control name this field maps to.")
out.append("    pub ui: &'static str,")
out.append("    /// Enum table name, if any.")
out.append("    pub enum_name: Option<&'static str>,")
out.append("    /// How confident the analysis is.")
out.append("    pub confidence: &'static str,")
out.append("    /// Free form notes from the analysis.")
out.append("    pub note: &'static str,")
out.append("}")
out.append("")
out.append("/// Every known .mib field, ordered by offset.")
out.append("pub static MIB_FIELDS: &[FieldDef] = &[")
out.extend(field_lines)
out.append("];")
out.append("")
out.extend(enum_lines)
out.append("/// Look up an enum table by name.")
out.append("pub fn enum_table(name: &str) -> Option<&'static [&'static str]> {")
out.append("    match name {")
for n, _ in enum_names:
    out.append('        "%s" => Some(ENUM_%s),' % (n, n.upper()))
out.append("        _ => None,")
out.append("    }")
out.append("}")
out.append("")
out.append("/// Read a little endian unsigned value of the given kind.")
out.append("pub fn read_u32(raw: &[u8], off: usize, kind: FieldKind) -> Option<u32> {")
out.append("    let n = match kind {")
out.append("        FieldKind::U8 | FieldKind::I8 => 1usize,")
out.append("        FieldKind::U16 | FieldKind::I16 => 2,")
out.append("        FieldKind::U32 | FieldKind::I32 | FieldKind::F32 => 4,")
out.append("        FieldKind::Bytes => return None,")
out.append("    };")
out.append("    if off + n > raw.len() {")
out.append("        return None;")
out.append("    }")
out.append("    let mut v = 0u32;")
out.append("    for i in 0..n {")
out.append("        v |= (raw[off + i] as u32) << (8 * i);")
out.append("    }")
out.append("    Some(v)")
out.append("}")
out.append("")
out.append("/// Write a little endian unsigned value of the given kind.")
out.append("pub fn write_u32(raw: &mut [u8], off: usize, kind: FieldKind, value: u32) -> bool {")
out.append("    let n = match kind {")
out.append("        FieldKind::U8 | FieldKind::I8 => 1usize,")
out.append("        FieldKind::U16 | FieldKind::I16 => 2,")
out.append("        FieldKind::U32 | FieldKind::I32 | FieldKind::F32 => 4,")
out.append("        FieldKind::Bytes => return false,")
out.append("    };")
out.append("    if off + n > raw.len() {")
out.append("        return false;")
out.append("    }")
out.append("    for i in 0..n {")
out.append("        raw[off + i] = ((value >> (8 * i)) & 0xFF) as u8;")
out.append("    }")
out.append("    true")
out.append("}")

os.makedirs(os.path.dirname(O), exist_ok=True)
open(O, "w", encoding="utf-8").write("\n".join(out))
print("wrote", O, os.path.getsize(O), "bytes")
print("mib fields:", len(mib), " enums:", len(enum_names))
for n, l in enum_names[:6]:
    print("   %-8s %d entries: %s" % (n, len(l), l[:3]))
kinds = {}
for f in mib:
    kinds[f.get("type")] = kinds.get(f.get("type"), 0) + 1
print("types:", kinds)
import glob
import os
import struct
import zlib

PLAYABLE_DIR = r"C:\anyWorkspace\nx\mhxx\arcs\all_event\playable"
DEAD_DIR = r"C:\anyWorkspace\nx\mhxx\arcs\all_event\dead"
SAVE_PATH = r"C:\Users\haruk\Downloads\system"
OUT_BIN = r"C:\anyWorkspace\nx\mhxx\mhnxeditor\crates\mhnx-core\src\official_dlc.bin"
OUT_RS = r"C:\anyWorkspace\nx\mhxx\mhnxeditor\crates\mhnx-core\src\dlc_bundle_gen.rs"


def parse_arc_title_and_id(b: bytes):
    assert b[:4] == b"ARC\x00"
    cnt = struct.unpack_from("<H", b, 6)[0]
    qid = 0
    title = ""
    for i in range(cnt):
        eo = 12 + i * 80
        th, csz, usz, doff = struct.unpack_from("<IIII", b, eo + 64)
        if th == 0x1BBFD18E:  # mib
            raw = zlib.decompress(b[doff : doff + csz])
            qid = struct.unpack_from("<i", raw, 0x0C)[0]
        elif th == 0x242BB29A:  # gmd
            raw = zlib.decompress(b[doff : doff + csz])
            klen = struct.unpack_from("<I", raw, 0x24)[0]
            sblock = raw[0x28 + klen + 1 :]
            title = sblock.split(b"\x00", 1)[0].decode("utf-8", "replace")
    return qid, title


def main():
    body = open(SAVE_PATH, "rb").read()
    if len(body) == 4_726_188:
        body = body[36:]
    assert len(body) == 4_726_152

    sec = struct.unpack_from("<I", body, 0x0C)[0]
    qbase = sec + 0x45F4
    ebase = sec + 0x1049F4

    # Map quest_id -> default slot (0..204) in the reference save
    slot_map = {}
    for slot in range(205):
        qid, sz = struct.unpack_from("<ii", body, qbase + slot * 0x1400)
        if qid != 0 and sz > 0:
            slot_map[qid] = slot

    blob = bytearray()

    # Categories:
    # 0 = Official (all 189 legitimate playable event & challenge quests)
    # 1 = Dead (34 unused / debug placeholder quests)
    quests = []
    for f in sorted(glob.glob(os.path.join(PLAYABLE_DIR, "*.arc"))):
        data = open(f, "rb").read()
        qid, title = parse_arc_title_and_id(data)
        assert qid > 0, f"bad qid in {f}"
        default_slot = slot_map.get(qid, 255)
        quests.append((0, default_slot, qid, title, data))

    for f in sorted(glob.glob(os.path.join(DEAD_DIR, "*.arc"))):
        data = open(f, "rb").read()
        qid, title = parse_arc_title_and_id(data)
        assert qid > 0, f"bad qid in {f}"
        default_slot = slot_map.get(qid, 255)
        quests.append((1, default_slot, qid, title, data))

    # Sort by category (Official first, then Dead) and by quest_id
    quests.sort(key=lambda x: (x[0], x[2]))

    quest_metas = []
    for cat, default_slot, qid, title, data in quests:
        off = len(blob)
        blob.extend(data)
        quest_metas.append((qid, cat, default_slot, off, len(data), title))

    # 2. Pack 40 Challenge Quest equipment records (+0x1049F4)
    equip_metas = []
    for slot in range(45):
        rec = body[ebase + slot * 0x800 : ebase + (slot + 1) * 0x800]
        qid, sz = struct.unpack_from("<ii", rec, 0)
        if qid != 0 and sz > 0:
            payload_len = min(8 + sz, 0x800)
            data = rec[:payload_len]
            off = len(blob)
            blob.extend(data)
            equip_metas.append((slot, qid, off, len(data)))

    # 3. Pack non-zero DLC section header slices in sec..sec+0x45F4
    hdr = bytearray(body[sec : sec + 0x45F4])
    for i in range(0x4C, 0x4C + 28):
        hdr[i] = 0

    nz_indices = [i for i, b in enumerate(hdr) if b != 0]
    ranges = []
    cur = None
    for i in nz_indices:
        if cur is None:
            cur = [i, i]
        elif i <= cur[1] + 16:
            cur[1] = i
        else:
            ranges.append(cur)
            cur = [i, i]
    if cur is not None:
        ranges.append(cur)

    hdr_metas = []
    for s, e in ranges:
        data = bytes(hdr[s : e + 1])
        off = len(blob)
        blob.extend(data)
        hdr_metas.append((s, off, len(data)))

    open(OUT_BIN, "wb").write(blob)

    c0 = sum(1 for q in quest_metas if q[1] == 0)
    c1 = sum(1 for q in quest_metas if q[1] == 1)
    assert (c0, c1) == (189, 34), f"got {(c0, c1)}"

    lines = [
        "//! Official & Unused MHXX DLC quest bundle (223 quests: 189 official + 34 dead/unused + 40 equipment records).",
        "//!",
        "//! Generated by tools/gen_official_dlc.py from C:\\anyWorkspace\\nx\\mhxx\\arcs\\all_event",
        "//! and the complete DLC section dump.",
        "",
        "/// Raw packed binary blob containing all 223 .arc files, 40 .equ records, and DLC header slices.",
        'pub static OFFICIAL_DLC_BLOB: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/official_dlc.bin"));',
        "",
        "/// Category of a bundled quest.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "#[repr(u8)]",
        "pub enum DlcQuestCategory {",
        "    /// All 189 official playable event & challenge quests.",
        "    Official = 0,",
        "    /// 34 unused / placeholder / debug template quests (没データ・予備枠).",
        "    Dead = 1,",
        "}",
        "",
        "/// Metadata for one bundled downloadable quest.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct OfficialQuestMeta {",
        "    /// Quest ID (e.g. 1010001, 1020001).",
        "    pub quest_id: i32,",
        "    /// Category (Official or Dead).",
        "    pub category: DlcQuestCategory,",
        "    /// Default quest slot index (0..204, or 255 if none).",
        "    pub default_slot: u8,",
        "    /// Byte offset inside OFFICIAL_DLC_BLOB.",
        "    pub offset: u32,",
        "    /// Byte length of the .arc file.",
        "    pub len: u16,",
        "    /// Japanese quest title from .gmd.",
        "    pub title: &'static str,",
        "}",
        "",
        "/// Metadata for one challenge quest equipment record.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct OfficialEquipMeta {",
        "    /// Equipment slot index (0..44).",
        "    pub slot: u8,",
        "    /// Associated challenge quest ID.",
        "    pub quest_id: i32,",
        "    /// Byte offset inside OFFICIAL_DLC_BLOB.",
        "    pub offset: u32,",
        "    /// Byte length of the record (including 8-byte id+size header).",
        "    pub len: u16,",
        "}",
        "",
        "/// Non-zero slice of the DLC section header (+0x0000..+0x45F4, excluding bitmask).",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct OfficialHeaderSlice {",
        "    /// Offset relative to DLC section start.",
        "    pub rel_offset: u16,",
        "    /// Byte offset inside OFFICIAL_DLC_BLOB.",
        "    pub offset: u32,",
        "    /// Byte length.",
        "    pub len: u16,",
        "}",
        "",
        f"/// All {len(quest_metas)} bundled DLC quests (189 Official + 34 Dead).",
        f"pub static OFFICIAL_QUESTS: [OfficialQuestMeta; {len(quest_metas)}] = [",
    ]

    cat_names = {
        0: "DlcQuestCategory::Official",
        1: "DlcQuestCategory::Dead",
    }
    for qid, cat, dslot, off, ln, title in quest_metas:
        esc = title.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(
            f'    OfficialQuestMeta {{ quest_id: {qid}, category: {cat_names[cat]}, default_slot: {dslot}, offset: {off}, len: {ln}, title: "{esc}" }},'
        )
    lines.append("];")
    lines.append("")

    lines.append(f"/// All {len(equip_metas)} official challenge quest equipment records.")
    lines.append(f"pub static OFFICIAL_EQUIPS: [OfficialEquipMeta; {len(equip_metas)}] = [")
    for slot, qid, off, ln in equip_metas:
        lines.append(
            f"    OfficialEquipMeta {{ slot: {slot}, quest_id: {qid}, offset: {off}, len: {ln} }},"
        )
    lines.append("];")
    lines.append("")

    lines.append("/// Non-zero slices of the DLC header area (+0x0000..+0x45F4).")
    lines.append(f"pub static OFFICIAL_HEADER_SLICES: [OfficialHeaderSlice; {len(hdr_metas)}] = [")
    for rel, off, ln in hdr_metas:
        lines.append(
            f"    OfficialHeaderSlice {{ rel_offset: 0x{rel:04X}, offset: {off}, len: {ln} }},"
        )
    lines.append("];")
    lines.append("")

    lines.extend([
        "/// Return the raw .arc bytes for an official quest metadata entry.",
        "#[inline]",
        "pub fn arc_bytes(meta: &OfficialQuestMeta) -> &'static [u8] {",
        "    let start = meta.offset as usize;",
        "    let end = start + meta.len as usize;",
        "    &OFFICIAL_DLC_BLOB[start..end]",
        "}",
        "",
        "/// Return the raw equipment record bytes for an official equipment metadata entry.",
        "#[inline]",
        "pub fn equip_bytes(meta: &OfficialEquipMeta) -> &'static [u8] {",
        "    let start = meta.offset as usize;",
        "    let end = start + meta.len as usize;",
        "    &OFFICIAL_DLC_BLOB[start..end]",
        "}",
        "",
        "/// Return the raw bytes for an official DLC header slice.",
        "#[inline]",
        "pub fn header_slice_bytes(meta: &OfficialHeaderSlice) -> &'static [u8] {",
        "    let start = meta.offset as usize;",
        "    let end = start + meta.len as usize;",
        "    &OFFICIAL_DLC_BLOB[start..end]",
        "}",
        "",
        "/// Look up a bundled quest by its quest ID.",
        "pub fn find_official_quest(quest_id: i32) -> Option<&'static OfficialQuestMeta> {",
        "    OFFICIAL_QUESTS.iter().find(|q| q.quest_id == quest_id)",
        "}",
        "",
        "/// Look up the Japanese title of a bundled quest by its quest ID.",
        "pub fn official_quest_title(quest_id: i32) -> Option<&'static str> {",
        "    find_official_quest(quest_id).map(|q| q.title)",
        "}",
    ])

    open(OUT_RS, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(
        f"Wrote {OUT_BIN} ({len(blob)} bytes) and {OUT_RS} ({c0} Official + {c1} Dead = {len(quest_metas)} quests)"
    )


if __name__ == "__main__":
    main()

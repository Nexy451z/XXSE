import re, os, json

# 1. Load skill_names from main.js
src = open(r"C:\anyWorkspace\nx\mhxx\refs\SJ-site\MHGU\save-manager\scripts\main.js", encoding="utf-8").read()
m = re.search(r"const skill_names = \[(.*?)\];", src, re.S)
body = m.group(1)
BT = chr(96)
pat = BT + r"([^" + BT + r"]*)" + BT + r'|"([^"]*)"' + r"|'([^']*)'"
names = re.findall(pat, body)
flat = [a or b or c for a, b, c in names]

# 2. Build EN -> JA dictionary from Kiranico Skill List HTML (or fallback JSON)
kiranico_html = r"C:\Users\haruk\Downloads\Skill List _ MHXX _ Kiranico _ モンスターハンターダブルクロス.html"
skills_json = r"C:\Users\haruk\Downloads\mhxx_skills_en_ja.json"

en_to_ja = {}

def clean(text):
    if not text:
        return ""
    t = re.sub(r'<[^>]+>', '', text).strip()
    t = re.sub(r'&nbsp;|\s*⚠\s*', '', t).strip()
    t = t.replace('&amp;', '&').replace('&quot;', '"').replace('&#39;', "'")
    t = re.sub(r'\s+', ' ', t)
    return t

if os.path.exists(kiranico_html):
    html = open(kiranico_html, "r", encoding="utf-8", errors="replace").read()
    pattern_a = re.compile(r'<a\s+href="https://mhxx\.kiranico\.com/en/skill/[^"]*"(?:\s+title="([^"]*)")?>\s*<ruby>(.*?)<rt>(.*?)</rt></ruby>\s*</a>', re.DOTALL)
    for title, jp, rt in pattern_a.findall(html):
        jp_clean = clean(jp)
        rt_clean = clean(rt)
        if rt_clean:
            en_to_ja[rt_clean] = jp_clean
        if title:
            title_clean = clean(title).replace(" [MHGU]", "").strip()
            if title_clean:
                en_to_ja[title_clean] = jp_clean

    pattern_ruby = re.compile(r'<ruby>(.*?)<rt>(.*?)</rt></ruby>', re.DOTALL)
    for jp, rt in pattern_ruby.findall(html):
        jp_clean = clean(jp)
        rt_clean = clean(rt)
        if rt_clean and rt_clean not in en_to_ja:
            en_to_ja[rt_clean] = jp_clean

    en_to_ja["Challenge Sheath"] = "挑戦者の納刀"
    en_to_ja["Bladescale Hone"] = "刃鱗磨き"

elif os.path.exists(skills_json):
    data = json.load(open(skills_json, "r", encoding="utf-8"))
    en_to_ja = data.get("map", {})

# Translate flat list to Japanese
ja_names = []
for n in flat:
    if n in en_to_ja:
        ja_names.append(en_to_ja[n])
    else:
        print(f"Warning: no translation for '{n}', keeping English")
        ja_names.append(n)

print("skill names: %d" % len(ja_names))
print("first 6:", ja_names[:6])
print("last 4:", ja_names[-4:])

out = []
out.append("//! Skill name table (Japanese), translated via MHXX Kiranico")
out.append("//! and aligned with the MHXX/MHGU Save Manager order.")
out.append("//!")
out.append("//! Charm records store 1-based skill ids; id 0 means \"no skill\".")
out.append("//!")
out.append("//! Generated by tools/gen_skills.py - do not edit by hand.")
out.append("")
out.append("/// Skill names, index = skill id - 1.")
out.append("pub static SKILL_NAMES: &[&str] = &[")
for n in ja_names:
    out.append('    "%s",' % n.replace("\\", "\\\\").replace('"', '\\"'))
out.append("];")
out.append("")
out.append("/// Look up a skill name by its 1-based id.")
out.append("pub fn skill_name(id: u8) -> Option<&'static str> {")
out.append("    if id == 0 {")
out.append("        return None;")
out.append("    }")
out.append("    SKILL_NAMES.get(id as usize - 1).copied()")
out.append("}")
path = r"C:\anyWorkspace\nx\mhxx\mhnxeditor\crates\mhnx-core\src\skills.rs"
open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
print("wrote", path, os.path.getsize(path), "bytes")

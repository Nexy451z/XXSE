
import re, os
src = open(r"C:\anyWorkspace\nx\mhxx\refs\SJ-site\MHGU\save-manager\scripts\DLC_CATS.js", encoding="utf-8").read()
def u8blocks(name):
    m = re.search(r"const " + name + r"\s*=\s*\[(.*?)\n\];", src, re.S)
    return [[int(x,0) for x in re.findall(r"0x[0-9a-fA-F]+|\d+", b.group(1))]
            for b in re.finditer(r"new Uint8Array\(\[(.*?)\]\)", m.group(1), re.S)]
en = u8blocks("EN_DLC_CAT_DATA"); jp = u8blocks("JP_DLC_CAT_DATA")
def nm(b):
    raw = bytes(b[:32]); z = raw.find(b'\x00')
    return raw[:z if z>=0 else 32].decode('utf-8', 'replace')

L = []
L.append("//! The 50 downloadable Palicoes (配信オトモ) released for MHXX/MHGU.")
L.append("//!")
L.append("//! Every record is 0x144 bytes and is copied verbatim into the shared block")
L.append("//! at save body + 0x2A. The Palico id lives at +0x5F and the name at +0x00,")
L.append("//! so a record identifies itself and we can index by id instead of by")
L.append("//! position (the game stores them in the order the player received them).")
L.append("//!")
L.append("//! Data extracted from the MHXX/MHGU Save Manager")
L.append("//! (https://github.com/SilverJolteon/SilverJolteon.github.io, MHGU/save-manager).")
L.append("//!")
L.append("//! Generated by tools/gen_dlcats.py - do not edit by hand.")
L.append("")
L.append("use alloc::string::String;")
L.append("use alloc::vec::Vec;")
L.append("")
L.append("/// Size of one Palico record.")
L.append("pub const RECORD_SIZE: usize = 0x144;")
L.append("/// Offset of the Palico id inside a record.")
L.append("pub const ID_OFFSET: usize = 0x5F;")
L.append("/// Length of the name field.")
L.append("pub const NAME_LEN: usize = 32;")
L.append("")
L.append("/// Which language a Palico belongs to.")
L.append("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
L.append("pub enum Lang {")
L.append("    /// English (MHGU) release.")
L.append("    En,")
L.append("    /// Japanese (MHXX) release.")
L.append("    Jp,")
L.append("}")
L.append("")
for tag, data in (("EN", en), ("JP", jp)):
    ids = [b[0x5F] for b in data]
    L.append("/// Palico ids available in the %s set." % tag)
    L.append("pub static %s_IDS: &[u8] = &[%s];" % (tag, ", ".join("0x%02X" % i for i in ids)))
    L.append("")
    L.append("/// Raw %s records, in the same order as %s_IDS." % (tag, tag))
    L.append("pub static %s_DATA: &[u8] = &[" % tag)
    for b in data:
        row = []
        for i in range(0, len(b), 16):
            row.append("    " + ", ".join("0x%02X" % x for x in b[i:i+16]) + ",")
        L.append("\n".join(row))
    L.append("];")
    L.append("")
L.append("/// Look up a record by language and id.")
L.append("pub fn record(lang: Lang, id: u8) -> Option<&'static [u8]> {")
L.append("    let (ids, data) = match lang {")
L.append("        Lang::En => (EN_IDS, EN_DATA),")
L.append("        Lang::Jp => (JP_IDS, JP_DATA),")
L.append("    };")
L.append("    let idx = ids.iter().position(|x| *x == id)?;")
L.append("    let o = idx * RECORD_SIZE;")
L.append("    data.get(o..o + RECORD_SIZE)")
L.append("}")
L.append("")
L.append("/// Name stored inside a record.")
L.append("pub fn record_name(rec: &[u8]) -> String {")
L.append("    let raw = &rec[..NAME_LEN.min(rec.len())];")
L.append("    let end = raw.iter().position(|b| *b == 0).unwrap_or(raw.len());")
L.append("    String::from_utf8_lossy(&raw[..end]).into_owned()")
L.append("}")
L.append("")
L.append("/// Id stored inside a record.")
L.append("pub fn record_id(rec: &[u8]) -> u8 {")
L.append("    rec.get(ID_OFFSET).copied().unwrap_or(0)")
L.append("}")
L.append("")
L.append("/// Every id that exists in either language, sorted.")
L.append("pub fn all_ids() -> Vec<u8> {")
L.append("    let mut v: Vec<u8> = Vec::new();")
L.append("    for id in EN_IDS.iter().chain(JP_IDS.iter()) {")
L.append("        if !v.contains(id) {")
L.append("            v.push(*id);")
L.append("        }")
L.append("    }")
L.append("    v.sort_unstable();")
L.append("    v")
L.append("}")
L.append("")

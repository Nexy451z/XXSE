#!/usr/bin/env python3
"""GameConstants.cs -> crates/mhnx-core/src/gamedata.rs  (manual parser, no regex escaping traps)"""
import re, os, sys

S = r"C:\anyWorkspace\nx\mhxx\save_editor\repos\MHXXSwitchSaveEditor\MHXXSaveEditor\Data\GameConstants.cs"
O = r"C:\anyWorkspace\nx\mhxx\mhnxeditor\crates\mhnx-core\src\gamedata.rs"

txt = open(S, encoding="utf-8-sig").read()
pat = re.compile(r"public\s+static\s+readonly\s+(string|int)\[\]\s+(\w+)\s*=\s*\{(.*?)\}\s*;", re.S)

def parse_cs_strings(body):
    vals = []
    i = 0
    n = len(body)
    while i < n:
        if body[i] == '"':
            i += 1
            buf = []
            while i < n and body[i] != '"':
                if body[i] == "\\" and i + 1 < n:
                    buf.append(body[i + 1])
                    i += 2
                else:
                    buf.append(body[i])
                    i += 1
            vals.append("".join(buf))
            i += 1
        else:
            i += 1
    return vals

def snake(n):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", n).upper()

def esc(v):
    return v.replace("\\", "\\\\").replace('"', '\\"')

items = []
for m in pat.finditer(txt):
    typ, name, body = m.group(1), m.group(2), m.group(3)
    vals = parse_cs_strings(body) if typ == "string" else re.findall(r"-?\d+", body)
    items.append((name, typ, vals))

out = []
out.append("//! Game data tables extracted from MHXXSaveEditor Data/GameConstants.cs")
out.append("//! @generated by tools/gen_names.py - DO NOT EDIT MANUALLY")
out.append("#![allow(clippy::all)]")
out.append("")
for name, typ, vals in items:
    rn = snake(name)
    if typ == "string":
        rust_ty = "&[&str]"
        body = ", ".join('"' + esc(v) + '"' for v in vals)
    else:
        rust_ty = "&[i32]"
        body = ", ".join(vals)
    out.append("/// C# %s (%d entries)" % (name, len(vals)))
    out.append("pub static %s: %s = &[%s];" % (rn, rust_ty, body))
    out.append("")
out.append("/// Linear search over a name table.")
out.append("#[inline]")
out.append("pub fn index_of(table: &[&str], name: &str) -> Option<usize> {")
out.append("    table.iter().position(|s| *s == name)")
out.append("}")

os.makedirs(os.path.dirname(O), exist_ok=True)
open(O, "w", encoding="utf-8").write("\n".join(out))
print("wrote", O, os.path.getsize(O), "bytes")
print("tables:", len(items))
for name, typ, vals in items[:10]:
    print("  %-34s %-6s %4d entries  first=%s" % (name, typ, len(vals), vals[:2]))

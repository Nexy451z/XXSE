/// The 依頼 name of one request record.
pub fn request_name(record: usize) -> Option<&'static str> {
    REQUEST_NAMES.get(record).copied()
}

/// The request record that owns this accept or complete flag, if any.
///
/// Flag 0 belongs to no request: the closing sentinel row carries it, and
/// calling that row a request would name an event that is not one.
fn request_of_flag(flag: u16) -> Option<usize> {
    if flag == 0 {
        return None;
    }
    REQUEST_ACCEPT_FLAGS
        .iter()
        .position(|f| *f == flag)
        .or_else(|| REQUEST_COMPLETE_FLAGS.iter().position(|f| *f == flag))
}

/// What a request flag number is: the record it belongs to, whether it is
/// the accept or the complete half, and the name. None when no request owns
/// the flag, which is the case for the 444 event bits the save shares.
pub fn request_flag_owner(flag: u16) -> Option<(usize, bool, &'static str)> {
    let record = request_of_flag(flag)?;
    let complete = REQUEST_COMPLETE_FLAGS.get(record).copied()? == flag;
    Some((record, complete, request_name(record).unwrap_or("")))
}

/// The quest name of one quest progress index (1..1508).
pub fn quest_name(index: usize) -> Option<&'static str> {
    if index == 0 {
        return None;
    }
    QUEST_NAMES.get(index).copied()
}

/// The ステージ name of one quest progress index, if the table has one.
pub fn quest_stage_name(index: usize) -> Option<&'static str> {
    let id = *QUEST_STAGE_IDS.get(index)?;
    stage_name(id)
}

/// The ステージ name of one stage id.
pub fn stage_name(id: u8) -> Option<&'static str> {
    STAGE_IDS
        .iter()
        .position(|s| *s == id)
        .and_then(|i| STAGE_NAMES.get(i).copied())
}
